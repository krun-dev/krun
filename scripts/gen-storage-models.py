#!/usr/bin/env python3
"""Generate persistence-only Bun models from the authoritative schema.sql."""
from __future__ import annotations
import argparse,hashlib,re,subprocess
from pathlib import Path

def split_columns(body: str) -> list[str]:
    values=[];start=0;depth=0;quote=False;i=0
    while i<len(body):
        char=body[i]
        if char=="'":
            if quote and i+1<len(body) and body[i+1]=="'":i+=2;continue
            quote=not quote
        elif not quote:
            if char=='(':depth+=1
            elif char==')':depth-=1
            elif char==',' and depth==0:values.append(body[start:i].strip());start=i+1
        i+=1
    values.append(body[start:].strip())
    return values

def go_name(value: str) -> str:
    acronyms={'id':'ID','url':'URL','uid':'UID','csrf':'CSRF','ip':'IP','sha256':'SHA256','s3':'S3','http':'HTTP','json':'JSON','api':'API','cli':'CLI'}
    return ''.join(acronyms.get(part,part.capitalize()) for part in value.split('_'))

def model_name(table: str) -> str:
    stem=table.removeprefix('krun_').removeprefix('worker_')
    replacements={'meta':'meta','identities':'identity','policies':'policy','entries':'entry','histories':'history','api_key_hashes':'api_key_hash'}
    if stem in replacements:stem=replacements[stem]
    elif stem.endswith('ies'):stem=stem[:-3]+'y'
    elif stem.endswith('s'):stem=stem[:-1]
    return go_name(stem)

def generate(root:Path) -> dict[str,str]:
    schema=(root/'internal/storage/schema.sql').read_bytes();text=re.sub(r'--[^\n]*','',schema.decode())
    groups:dict[str,list[str]]={};registry=[]
    for table,body in re.findall(r'CREATE TABLE IF NOT EXISTS (\w+)\s*\((.*?)\);',text,re.S):
        parts=split_columns(body);primary=set()
        for part in parts:
            match=re.match(r'PRIMARY KEY\s*\(([^)]+)\)',part,re.I)
            if match:primary.update(x.strip() for x in match[1].split(','))
        cols=[]
        for part in parts:
            match=re.match(r'(\w+)\s+(text\[\]|text|jsonb|bytea|bigint|integer|boolean|timestamptz|double precision|numeric)(?=\s|$)(.*)',part,re.I|re.S)
            if not match:
                if re.match(r'(PRIMARY|UNIQUE|CHECK|CONSTRAINT)\b',part,re.I):continue
                raise ValueError(f'{table}: unsupported column: {part}')
            name,sql_type,extra=match.groups();sql_type=sql_type.lower()
            pk=name in primary or 'PRIMARY KEY' in extra.upper()
            nullable=not pk and 'NOT NULL' not in extra.upper()
            typ={'text':'string','text[]':'[]string','jsonb':'json.RawMessage','bytea':'[]byte','bigint':'int64','integer':'int','boolean':'bool','timestamptz':'time.Time','double precision':'float64','numeric':'float64'}[sql_type]
            if nullable and typ in ['string','int','int64','bool','float64','time.Time']:typ='*'+typ
            tags=[name]
            if pk:tags.append('pk')
            if sql_type=='jsonb':tags.append('type:jsonb')
            if sql_type=='text[]':tags.append('array')
            cols.append(f'\t{go_name(name)} {typ} `bun:"{",".join(tags)}"`')
        name=model_name(table);registry.append(name)
        group='workers' if table.startswith('krun_worker_') else 'config' if table.startswith('worker_config_') else 'runtime' if table.startswith('worker_') else 'repository' if 'repository_' in table else 'auth' if any(word in table for word in ['sessions','browsers','login_states','email_logins','device_codes','rate_limits']) else 'iam'
        groups.setdefault(group,[]).append(f'type {name} struct {{\n\tbun.BaseModel `bun:"table:{table},alias:{table}"`\n'+ '\n'.join(cols)+'\n}')
    outputs={};header='// Code generated by scripts/gen-storage-models.py from schema.sql; DO NOT EDIT.\n'
    for group,decls in groups.items():
        body='\n\n'.join(decls);imports=['"github.com/uptrace/bun"']
        if 'json.' in body:imports.insert(0,'"encoding/json"')
        if 'time.' in body:imports.insert(0,'"time"')
        standard=sorted(imp for imp in imports if 'github.com' not in imp)
        outputs[group+'_gen.go']=header+'package models\nimport (\n'+'\n'.join(standard)+'\n\n\"github.com/uptrace/bun\"\n)\n\n'+body+'\n'
    digest=hashlib.sha256(schema).hexdigest()
    outputs['registry_gen.go']=header+'package models\n\nconst SchemaSHA256 = "'+digest+'"\n\nfunc All() []any { return []any{\n'+',\n'.join('(*'+name+')(nil)' for name in registry)+',\n} }\n'
    return {name:subprocess.run(['gofmt'],input=value,text=True,capture_output=True,check=True).stdout for name,value in outputs.items()}

def main() -> None:
    parser=argparse.ArgumentParser();parser.add_argument('--root',type=Path,default=Path(__file__).resolve().parents[1]);parser.add_argument('--output',type=Path);parser.add_argument('--check',action='store_true');args=parser.parse_args()
    root=args.root.resolve();output=args.output or root/'internal/storage/models';files=generate(root)
    if args.check:
        stale=[name for name,text in files.items() if not (output/name).exists() or (output/name).read_text()!=text]
        extra={p.name for p in output.glob('*_gen.go')}-files.keys()
        if stale or extra:raise SystemExit('storage models are stale; run go generate ./internal/storage/models: '+', '.join(sorted(set(stale)|extra)))
        print('storage ORM models match schema.sql');return
    output.mkdir(parents=True,exist_ok=True)
    for path in output.glob('*_gen.go'):
        if path.name not in files:path.unlink()
    for name,text in files.items():(output/name).write_text(text)
    print('Generated',len(files),'model files from schema.sql')
if __name__=='__main__':main()
